def add(num_1: int, num_2: int) -> int:
    """
    Adds two numbers.
    :param num_1: The first number being added.
    :param num_2: The second number being added.
    :return: The sum of the two numbers.
    """
    return num_1 + num_2

def subtract(num_1: int, num_2: int) -> int:
    """
    Subtracts one number from another.
    :param num_1: Number being subtracted from.
    :param num_2: Number being subtracted.
    :return: The difference.
    """
    return num_1 - num_2

def multiply(num_1: int, num_2: int) -> int:
    """
    Multiplies two numbers.
    :param num_1: The first factor.
    :param num_2: The second factor.
    :return: The product.
    """
    return num_1 * num_2

def divide(num_1: int, num_2: int) -> float:
    """
    Divides one number by another.
    :param num_1: The numerator.
    :param num_2: The denominator.
    :return: The quotient.
    """
    return num_1 / num_2