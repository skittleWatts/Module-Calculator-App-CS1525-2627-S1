from operations import add, subtract, multiply, divide


#Test add operation.
test_sum = add(5, 7)
print(f"The sum of 5 and 7 is {test_sum}.")

#Test subtract operation.
test_difference = subtract(10, 6)
print(f"The difference of 10 and 6 is {test_difference}.")

#Test multiply operation.
test_product = multiply(3, 4)
print(f"The product of 3 and 4 is {test_product}.")

#Test divide operation.
test_quotient = divide(6, 4)
print(f"The quotient of 6 and 4 is {test_quotient}.")


